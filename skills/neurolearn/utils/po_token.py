"""PO Token (bgutil) readiness probe — shared by `doctor` and the setup wizard.

The bgutil-ytdlp-pot-provider PIP plugin auto-registers with yt-dlp, but a
PO Token is only actually minted when a PROVIDER is running — most reliably
the bgutil HTTP server on 127.0.0.1:4416. Node presence alone is NOT enough
(the pre-v0.18.1 check conflated them). This module reports the honest
readiness so both the doctor JSON and the wizard can branch on it.

Setup paths:
  - Docker (no local Node needed): DOCKER_RUN_CMD below.
  - Native (Node >= 22 or Deno):   NATIVE_SETUP_URL below.
"""
from __future__ import annotations

import http.client
import importlib.metadata
import json
import re
import shutil
import socket
import subprocess

from packaging.version import InvalidVersion, Version

POT_SERVER_HOST = "127.0.0.1"
POT_SERVER_PORT = 4416
NODE_MIN_MAJOR = 22  # bgutil-ytdlp-pot-provider 2.x native server requirement

DOCKER_RUN_CMD = (
    "docker run --name bgutil-provider -d --init --restart unless-stopped "
    "-p 127.0.0.1:4416:4416 brainicism/bgutil-ytdlp-pot-provider:2.0.2"
)
NATIVE_SETUP_URL = "https://github.com/Brainicism/bgutil-ytdlp-pot-provider#installation"


def _node_version() -> tuple[bool, str | None, int | None]:
    """Return (node_available, version_string, major_int)."""
    if not shutil.which("node"):
        return False, None, None
    try:
        out = subprocess.run(
            ["node", "--version"], capture_output=True, text=True, timeout=5,
        )
        ver = (out.stdout or "").strip() or None
        m = re.search(r"v?(\d+)", ver or "")
        return True, ver, (int(m.group(1)) if m else None)
    except Exception:
        return True, None, None


def plugin_version() -> str | None:
    try:
        return importlib.metadata.version("bgutil-ytdlp-pot-provider")
    except importlib.metadata.PackageNotFoundError:
        return None


def plugin_installed() -> bool:
    return plugin_version() is not None


def server_reachable(
    host: str = POT_SERVER_HOST, port: int = POT_SERVER_PORT, *, timeout: float = 0.3,
) -> bool:
    """True when a provider is listening on the bgutil port."""
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


def _server_version() -> str | None:
    """Read a bounded /ping reply from the fixed loopback provider only.

    HTTPConnection bypasses environment proxies and does not follow redirects.
    No token is generated by this endpoint.
    """
    connection = http.client.HTTPConnection(POT_SERVER_HOST, POT_SERVER_PORT, timeout=0.5)
    try:
        connection.request("GET", "/ping")
        response = connection.getresponse()
        if response.status != 200:
            return None
        data = response.read(4097)
        if len(data) > 4096:
            return None
        payload = json.loads(data)
        version = payload.get("version") if isinstance(payload, dict) else None
        if not isinstance(version, str):
            return None
        return str(Version(version))
    except (OSError, http.client.HTTPException, ValueError):
        return None
    finally:
        connection.close()


def status() -> dict:
    """Honest PO Token readiness snapshot for doctor / wizard."""
    node_available, node_version, node_major = _node_version()
    node_ok = node_major is not None and node_major >= NODE_MIN_MAJOR
    installed_version = plugin_version()
    reachable = server_reachable()
    server_version = _server_version() if reachable else None
    compatible = False
    if installed_version is not None and server_version is not None:
        try:
            # bgutil's own HTTP provider rejects different major versions.
            compatible = Version(installed_version).major == Version(server_version).major
        except InvalidVersion:
            pass
    return {
        "node_available": node_available,
        "node_version": node_version,
        "node_ok": node_ok,  # Node >= NODE_MIN_MAJOR
        "po_token_plugin_installed": installed_version is not None,
        "po_token_plugin_version": installed_version,
        "po_token_server_reachable": reachable,
        "po_token_server_version": server_version,
        "po_token_server_compatible": compatible,
        # An open TCP port alone does not prove this is a usable provider.
        "po_token_can_generate": reachable and compatible,
    }
